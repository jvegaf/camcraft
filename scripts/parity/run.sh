#!/usr/bin/env bash
# The parity harness of E0.4: measure the committed corpus and compare it against its goldens.
#
#   scripts/parity/run.sh            # measure and compare; non-zero on any divergence
#   scripts/parity/run.sh --update   # re-pin the goldens to what the tree measures now
#
# What it is for. `fixtures/corpus/` is a fixed set of real fabrication artefacts; a golden per board
# records what this tree makes of each of them — how many polygons, how much area, how many points after
# flattening — and the comparison fails when that changes. That is the instrument the roadmap asks for
# before any PCB operation is judged: the day a layer that used to be refused starts being read, the
# diff is the proof, and the day a layer that used to be read is refused, it is the alarm.
#
# It is not a claim of parity with FlatCAM. Comparing against an external oracle is the level D5 asks
# for and needs an oracle that runs here; what this harness compares against is this tree's own
# recorded output, which is what "fails on divergence" means in E0.4's exit criterion.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)
CORPUS="$ROOT/fixtures/corpus"
MEASURE_DIR="$ROOT/scripts/parity/measure"
TARGET="$ROOT/target/parity"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

UPDATE=0
# `--update` rewrites the goldens; every other invocation is a check. The count is part of the match on
# purpose: `run.sh --update --check` must not quietly become a write because the first argument happened
# to be the accepting one.
case "$#:${1:-}" in
0:) ;;
1:--update) UPDATE=1 ;;
*)
  echo "usage: scripts/parity/run.sh [--update]" >&2
  echo "  no argument measures and compares; --update re-pins the goldens" >&2
  exit 2
  ;;
esac

if [ ! -d "$CORPUS" ]; then
  echo "ERROR: $CORPUS is missing; the corpus is committed and is not generated by this script." >&2
  echo "       scripts/parity/export.sh regenerates it from the KiCad demo boards, deliberately." >&2
  exit 1
fi

echo "== building the measurer"
# The measurer lives outside the workspace on purpose (see scripts/parity/README.md), so it is built
# here and its target directory is the workspace's own, which is already ignored by git.
# `--locked` on purpose: the measurer pins its own lock file, and resolving a newer version
# here would change what the corpus is measured with without saying so.
CARGO_TARGET_DIR="$TARGET" cargo build --manifest-path "$MEASURE_DIR/Cargo.toml" --locked --release --quiet
MEASURE="$TARGET/release/parity-measure"
if [ ! -x "$MEASURE" ]; then
  echo "ERROR: $MEASURE was not built" >&2
  exit 1
fi

echo "== measuring $CORPUS"
python3 "$ROOT/scripts/parity/collect.py" "$CORPUS" "$MEASURE" >"$WORK/measured.json"

# A non-zero exit of the measurer is a crash, and a crash must never become a golden: `--update` would
# re-pin it as a state that looks like a reader refusal forever after. This runs before either branch, so
# the gate and the re-pin both stop here instead of comparing a failure with a failure.
if ! python3 "$ROOT/scripts/parity/guard_errors.py" "$WORK/measured.json"; then
  echo "ERROR: a measurer failure is not a corpus divergence; fix the crash and re-run" >&2
  exit 1
fi

if [ "$UPDATE" = "1" ]; then
  python3 - "$WORK/measured.json" "$CORPUS" <<'PY'
import json, sys
from pathlib import Path

measured_path, corpus = Path(sys.argv[1]), Path(sys.argv[2])
measured = json.loads(measured_path.read_text(encoding="utf-8"))
header = {
    "flatten_tolerance_mm": measured["flatten_tolerance_mm"],
    "timeout_seconds": measured["timeout_seconds"],
}
for slug, artefacts in sorted(measured["boards"].items()):
    golden = {**header, "artefacts": artefacts}
    path = corpus / slug / "parity.json"
    path.write_text(json.dumps(golden, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"  pinned {path.relative_to(corpus.parent.parent)}")
PY
  echo "== goldens updated; review their diff before committing"
  exit 0
fi

echo "== comparing against the goldens"
python3 "$ROOT/scripts/parity/compare.py" "$CORPUS" "$WORK/measured.json"
