#!/usr/bin/env bash
# The FlatCAM baseline of E0.6: measure the committed corpus with FlatCAM-Plus and compare it against its
# goldens.
#
#   scripts/baseline/run.sh            # measure and compare; non-zero on any divergence
#   scripts/baseline/run.sh --update   # re-pin the goldens to what FlatCAM measures now
#
# FlatCAM is a separate Python environment, so this script needs one:
#
#   FLATCAM_PYTHON=~/Code/FlatCAM-Plus/.venv/bin/python scripts/baseline/run.sh
#
# `FLATCAM_PYTHON` defaults to `~/Code/FlatCAM-Plus/.venv/bin/python`, and the script refuses to run
# against an interpreter that cannot import FlatCAM rather than measuring nothing slowly.
#
# What it is for. `fixtures/corpus/` is a fixed set of real fabrication artefacts, and the roadmap asks for
# the cost of reading them — times and move counts, per board and per operation — recorded as versioned
# goldens before any PCB operation is judged: F4 is not written until E0.6 is green, because without a
# baseline the product's promise is not measurable. Before this existed, "FlatCAM handles the corpus" was
# an assumption; the parity goldens pinned what *this* tree does and nothing pinned what the reference
# implementation does with the same files.
#
# It is not a parity check and it never runs in CI: it needs FlatCAM's own Python 3.14 + PyQt6 + Shapely
# environment, and half of what it records is wall time on one machine (see `README.md`).
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)
CORPUS="$ROOT/fixtures/corpus"
BASELINE="$ROOT/fixtures/baseline"
PYTHON="${FLATCAM_PYTHON:-$HOME/Code/FlatCAM-Plus/.venv/bin/python}"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

UPDATE=0
# `--update` rewrites the goldens; every other invocation is a check. The count is part of the match on
# purpose: `run.sh --update --check` must not quietly become a write because the first argument happened
# to be the accepting one.
case "$#:${1:-}" in
0:) ;;
1:--update) UPDATE=1 ;;
*)
  echo "usage: scripts/baseline/run.sh [--update]" >&2
  echo "  no argument measures and compares; --update re-pins the goldens" >&2
  exit 2
  ;;
esac

if [ ! -d "$CORPUS" ]; then
  echo "ERROR: $CORPUS is missing; the corpus is committed and is not generated by this script." >&2
  exit 1
fi

if [ ! -x "$PYTHON" ]; then
  echo "ERROR: FlatCAM's interpreter is not executable: $PYTHON" >&2
  echo "       Set FLATCAM_PYTHON to the python of a FlatCAM-Plus checkout, e.g." >&2
  echo "       FLATCAM_PYTHON=~/Code/FlatCAM-Plus/.venv/bin/python scripts/baseline/run.sh" >&2
  exit 1
fi

echo "== measuring with the FlatCAM environment"
# Cheaper to fail here than to boot sixty-six processes that each die on an import.
if ! "$PYTHON" -c 'import flatcam_plus, shapely, PyQt6.QtCore' >/dev/null 2>&1; then
  echo "ERROR: $PYTHON cannot import flatcam_plus, shapely and PyQt6; that is not a FlatCAM environment" >&2
  exit 1
fi
"$PYTHON" - "$PYTHON" <<'PY'
import sys

# The version is printed because it is part of what a golden means: a measurement from another FlatCAM
# is a different baseline, and the comparison refuses to mix them.
from flatcam_plus import version as flatcam_version

print(f"  {sys.executable}")
print(f"  FlatCAM {flatcam_version.__version__} on Python {sys.version.split()[0]}")
PY

# `BASELINE_BOARDS` narrows a run to some boards while developing the instrument; a re-pin over a subset
# would leave the other goldens describing another FlatCAM, so `--update` refuses to take it.
BOARDS=()
if [ -n "${BASELINE_BOARDS:-}" ]; then
  if [ "$UPDATE" = "1" ]; then
    echo "ERROR: BASELINE_BOARDS with --update would pin a partial baseline; measure everything to re-pin" >&2
    exit 2
  fi
  read -r -a BOARDS <<<"${BASELINE_BOARDS//,/ }"
fi

echo "== measuring $CORPUS"
# `/usr/bin/python3` and not `$PYTHON` on purpose: these two scripts are ordinary Python and must not run
# inside the FlatCAM environment, which is the thing being measured.
if ! /usr/bin/env python3 "$ROOT/scripts/baseline/collect.py" "$CORPUS" "$PYTHON" "${BOARDS[@]+"${BOARDS[@]}"}" \
  >"$WORK/measured.json"; then
  # A non-zero exit here is a crashed measurement (or a missing interpreter), and a crash must never
  # become a golden: `--update` would pin it as a state that looks like a FlatCAM refusal forever after.
  echo "ERROR: the measurement failed; a crash is not a baseline. See the reasons above." >&2
  exit 1
fi

if [ "$UPDATE" = "1" ]; then
  python3 "$ROOT/scripts/baseline/pin.py" "$WORK/measured.json" "$BASELINE"
  echo "== goldens updated; review their diff before committing"
  exit 0
fi

echo "== comparing against the goldens"
python3 "$ROOT/scripts/baseline/compare.py" "$CORPUS" "$BASELINE" "$WORK/measured.json"
